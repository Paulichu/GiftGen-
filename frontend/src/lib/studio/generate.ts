function file(path: string, language: string, content: string): GeneratedFile {
  return { path, language, content, bytes: Buffer.byteLength(content, "utf8") };
}

export function generateFiles(blueprint: Blueprint, jobId: string): GeneratedFile[] {
  const schema = {
    app: blueprint.title,
    description: blueprint.description,
    appType: blueprint.appType,
    entity: blueprint.entity,
    fields: blueprint.fields,
    features: blueprint.features,
    theme: blueprint.theme,
    storageKey: `studio.${jobId}.data`,
  };

  if (blueprint.appType === "landing") {
    return [
      file("index.html", "html", landingHtml(blueprint)),
      file("styles.css", "css", landingStyles(blueprint)),
      file("app.js", "javascript", LANDING_RUNTIME),
      file("schema.json", "json", JSON.stringify(schema, null, 2)),
      file("README.md", "markdown", appReadme(blueprint, jobId)),
    ];
  }

  const config = appConfig(blueprint, jobId);
  const js = `var CONFIG = ${JSON.stringify(config, null, 2)};\n\n${APP_RUNTIME}`;

  return [
    file("index.html", "html", appHtml(blueprint)),
    file("styles.css", "css", appStyles(blueprint)),
    file("app.js", "javascript", js),
    file("schema.json", "json", JSON.stringify(schema, null, 2)),
    file("README.md", "markdown", appReadme(blueprint, jobId)),
  ];
}
